local wow = require("spec.support.wow")

local function item(name, extra)
  local t = { link = "[" .. name .. "]", name = name, quality = 4, quantity = 1,
    candidates = { "Alice", "Bob-Realm", "Unknown", "Masterlooter" } }
  for k, v in pairs(extra or {}) do t[k] = v end
  return t
end

local function line(who, name, suffix)
  return who .. " receives loot: [" .. name .. "]" .. (suffix or "") .. "."
end

describe("Tracking", function()
  local ns, events

  before_each(function()
    ns = wow.start()
    events = {}
    for _, name in ipairs({ "confirmed", "unconfirmed", "late", "outside" }) do
      ns.Tracking.On(name, function(info) events[#events + 1] = { name, info } end)
    end
  end)

  local function names()
    local list = {}
    for _, e in ipairs(events) do list[#list + 1] = e[1] end
    return list
  end

  it("hands the item over and confirms once the slot clears and the loot line shows", function()
    wow.openLoot({ item("Choker") })
    local attempt = ns.Tracking.Give(1, 1)
    assert.are.same({ { slot = 1, candidate = 1 } }, wow.gives)
    assert.are.equal("Alice", attempt.winner)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    assert.are.same({}, events)
    wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
    assert.are.same({ "confirmed" }, names())
    assert.are.equal(attempt, events[1][2])
    wow.advance(10)
    assert.are.same({ "confirmed" }, names())
  end)

  it("counts the slot clear once when the game fires it twice", function()
    wow.openLoot({ item("Choker"), item("Choker") })
    ns.Tracking.Give(1, 1)
    ns.Tracking.Give(2, 1)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
    assert.are.same({ "confirmed" }, names())
    assert.are.equal(2, ns.Tracking.Pending()[1].slot)
    assert.is_nil(ns.Tracking.Pending()[1].cleared)
  end)

  it("accepts the clear and the loot line in either order", function()
    wow.openLoot({ item("Choker") })
    ns.Tracking.Give(1, 2)
    wow.fire("CHAT_MSG_LOOT", line("Bob", "Choker"))
    assert.are.same({}, events)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    assert.are.same({ "confirmed" }, names())
  end)

  it("reports not confirmed after the wait if either sign is missing", function()
    wow.openLoot({ item("Choker") })
    ns.Tracking.Give(1, 1)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    wow.advance(ns.Tracking.confirmWait - 1)
    assert.are.same({}, events)
    wow.advance(1)
    assert.are.same({ "unconfirmed" }, names())
    assert.is_true(events[1][2].cleared)
    assert.is_nil(events[1][2].chat)
  end)

  it("tells identical copies apart, even for the same winner", function()
    wow.openLoot({ item("Choker"), item("Choker") })
    ns.Tracking.Give(1, 1)
    ns.Tracking.Give(2, 1)
    wow.fire("LOOT_SLOT_CLEARED", 2)
    wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
    assert.are.same({ "confirmed" }, names())
    assert.are.equal(2, events[1][2].slot)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
    assert.are.same({ "confirmed", "confirmed" }, names())
    assert.are.equal(1, events[2][2].slot)
  end)

  it("matches stacks by their quantity", function()
    wow.openLoot({ item("Thorium Bar", { quality = 1, quantity = 2 }) })
    ns.Tracking.Give(1, 1)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    wow.fire("CHAT_MSG_LOOT", line("Alice", "Thorium Bar"))
    assert.are.same({}, events)
    wow.fire("CHAT_MSG_LOOT", line("Alice", "Thorium Bar", "x2"))
    assert.are.same({ "confirmed" }, names())
  end)

  it("reads real item links and 'You receive'", function()
    local link = "|cffa335ee|Hitem:19019::::::::60:::::|h[Thunderfury]|h|r"
    wow.openLoot({ item("Thunderfury", { link = link }) })
    ns.Tracking.Give(1, 4)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    wow.fire("CHAT_MSG_LOOT", "You receive loot: " .. link .. ".")
    assert.are.same({ "confirmed" }, names())
  end)

  it("ignores a loot line for another winner or item", function()
    wow.openLoot({ item("Choker") })
    ns.Tracking.Give(1, 1)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    wow.fire("CHAT_MSG_LOOT", line("Bob", "Choker"))
    wow.fire("CHAT_MSG_LOOT", line("Alice", "Ring"))
    wow.fire("CHAT_MSG_LOOT", "Alice creates [Choker].")
    assert.are.same({}, events)
  end)

  describe("a late confirmation", function()
    it("after the wait reports 'late' once both signs are in, in either order", function()
      wow.openLoot({ item("Choker"), item("Ring") })
      ns.Tracking.Give(1, 1)
      ns.Tracking.Give(2, 1)
      wow.advance(ns.Tracking.confirmWait)
      wow.fire("LOOT_SLOT_CLEARED", 1)
      assert.are.same({ "unconfirmed", "unconfirmed" }, names())
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Ring"))
      wow.fire("LOOT_SLOT_CLEARED", 2)
      assert.are.same({ "unconfirmed", "unconfirmed", "late", "late" }, names())
      assert.is_falsy(events[3][2].superseded)
    end)

    it("is not given for a loot line alone", function()
      wow.openLoot({ item("Choker") })
      ns.Tracking.Give(1, 1)
      wow.advance(ns.Tracking.confirmWait)
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      assert.are.same({ "unconfirmed" }, names())
    end)

    it("after the item was handed out again says so, and leaves the new attempt alone", function()
      wow.openLoot({ item("Choker") })
      local first = ns.Tracking.Give(1, 1)
      wow.advance(ns.Tracking.confirmWait)
      local second = ns.Tracking.Give(1, 2)
      assert.is_true(first.superseded)
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      wow.fire("LOOT_SLOT_CLEARED", 1)
      -- The clear goes to the newer attempt, so Alice's stays open.
      assert.are.same({ "unconfirmed" }, names())
      assert.are.equal("pending", second.status)
    end)

    it("confirms the re-award when its own clear and loot line arrive", function()
      wow.openLoot({ item("Choker") })
      ns.Tracking.Give(1, 1)
      wow.advance(ns.Tracking.confirmWait)
      ns.Tracking.Give(1, 2)
      wow.fire("LOOT_SLOT_CLEARED", 1)
      wow.fire("CHAT_MSG_LOOT", line("Bob", "Choker"))
      assert.are.same({ "unconfirmed", "confirmed" }, names())
      assert.are.equal("Bob", events[2][2].winner)
    end)

    it("is not reported twice", function()
      wow.openLoot({ item("Choker") })
      ns.Tracking.Give(1, 1)
      wow.advance(ns.Tracking.confirmWait)
      wow.fire("LOOT_SLOT_CLEARED", 1)
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      assert.are.same({ "unconfirmed", "late" }, names())
    end)
  end)

  describe("when the loot window closes mid-attempt", function()
    it("confirms on the loot line alone", function()
      wow.openLoot({ item("Choker") })
      ns.Tracking.Give(1, 1)
      wow.closeLoot()
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      assert.are.same({ "confirmed" }, names())
    end)

    it("confirms when the line came first", function()
      wow.openLoot({ item("Choker") })
      ns.Tracking.Give(1, 1)
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      wow.closeLoot()
      assert.are.same({ "confirmed" }, names())
    end)

    it("still reports not confirmed without the line", function()
      wow.openLoot({ item("Choker") })
      ns.Tracking.Give(1, 1)
      wow.closeLoot()
      wow.advance(ns.Tracking.confirmWait)
      assert.are.same({ "unconfirmed" }, names())
    end)
  end)

  describe("when slots shift", function()
    it("follows the item to its new slot after the window reopens", function()
      wow.openLoot({ item("Ring"), item("Choker") })
      ns.Tracking.Give(2, 1)
      wow.openLoot({ item("Choker"), item("Ring") })
      wow.fire("LOOT_SLOT_CLEARED", 2) -- the ring: not ours
      assert.are.same({}, events)
      wow.fire("LOOT_SLOT_CLEARED", 1)
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      assert.are.same({ "confirmed" }, names())
    end)

    it("falls back to the loot line alone if the item is gone from the reopened window", function()
      wow.openLoot({ item("Choker") })
      ns.Tracking.Give(1, 1)
      wow.openLoot({ item("Ring") })
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      assert.are.same({ "confirmed" }, names())
    end)

    it("does not take another slot's clear for the attempt", function()
      wow.openLoot({ item("Ring"), item("Choker") })
      ns.Tracking.Give(2, 1)
      wow.fire("LOOT_SLOT_CLEARED", 1)
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      assert.are.same({}, events)
    end)
  end)

  it("follows rapid awards one after another", function()
    wow.openLoot({ item("Choker"), item("Ring"), item("Cloak") })
    ns.Tracking.Give(1, 1)
    ns.Tracking.Give(2, 2)
    ns.Tracking.Give(3, 1)
    wow.fire("LOOT_SLOT_CLEARED", 2)
    wow.fire("LOOT_SLOT_CLEARED", 1)
    wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
    wow.fire("CHAT_MSG_LOOT", line("Bob", "Ring"))
    wow.advance(ns.Tracking.confirmWait)
    assert.are.same({ "confirmed", "confirmed", "unconfirmed" }, names())
    assert.are.equal(3, events[3][2].slot)
    assert.are.equal(3, #wow.gives)
  end)

  describe("a hand-out nobody started here", function()
    it("is reported as outside at or above the loot threshold", function()
      wow.openLoot({ item("Choker", { quality = 3 }) })
      wow.fire("LOOT_SLOT_CLEARED", 1)
      wow.fire("LOOT_SLOT_CLEARED", 1)
      wow.fire("CHAT_MSG_LOOT", line("Bob-Realm", "Choker"))
      assert.are.same({ "outside" }, names())
      assert.are.same({ winner = "Bob", link = "[Choker]", quantity = 1, quality = 3 }, events[1][2])
    end)

    it("is reported when the loot line comes first", function()
      wow.openLoot({ item("Choker") })
      wow.fire("CHAT_MSG_LOOT", line("Bob", "Choker"))
      wow.fire("LOOT_SLOT_CLEARED", 1)
      assert.are.same({ "outside" }, names())
    end)

    it("is ignored below the threshold", function()
      wow.openLoot({ item("Linen", { quality = 1 }) })
      wow.fire("LOOT_SLOT_CLEARED", 1)
      wow.fire("CHAT_MSG_LOOT", line("Bob", "Linen"))
      assert.are.same({}, events)
    end)

    it("needs both signs, and forgets a lone one after the wait", function()
      wow.openLoot({ item("Choker") })
      wow.fire("CHAT_MSG_LOOT", line("Bob", "Choker"))
      wow.advance(ns.Tracking.confirmWait + 1)
      wow.fire("LOOT_SLOT_CLEARED", 1)
      assert.are.same({}, events)
    end)

    it("is not reported for an item the add-on handed out", function()
      wow.openLoot({ item("Choker") })
      ns.Tracking.Give(1, 1)
      wow.fire("LOOT_SLOT_CLEARED", 1)
      wow.fire("CHAT_MSG_LOOT", line("Alice", "Choker"))
      assert.are.same({ "confirmed" }, names())
    end)
  end)

  describe("refuses", function()
    it("a candidate the game can't name yet", function()
      wow.openLoot({ item("Choker") })
      local attempt, reason = ns.Tracking.Give(1, 3)
      assert.is_nil(attempt)
      assert.are.equal("unknown", reason)
      assert.are.same({}, wow.gives)
    end)

    it("a grey item for someone else, but not for the looter", function()
      wow.openLoot({ item("Rag", { quality = 0 }) })
      local _, reason = ns.Tracking.Give(1, 1)
      assert.are.equal("grey", reason)
      assert.is_table(ns.Tracking.Give(1, 4))
    end)

    it("a slot that is empty or already cleared", function()
      wow.openLoot({ item("Choker") })
      assert.are.equal("empty", select(2, ns.Tracking.Give(2, 1)))
      wow.fire("LOOT_SLOT_CLEARED", 1)
      assert.are.equal("empty", select(2, ns.Tracking.Give(1, 1)))
    end)
  end)
end)
