local Release = dofile("release/Release.lua")

local function pr(number, title, body)
  return { number = number, title = title, body = body or "" }
end

describe("Release.nextVersion", function()
  local function bump(...) return Release.nextVersion("1.2.3", { ... }) end

  it("raises the patch for a fix", function()
    assert.equal("1.2.4", bump(pr(1, "fix: stop the crash")))
  end)
  it("raises the minor for a feature", function()
    assert.equal("1.3.0", bump(pr(1, "feat(ui): new window")))
  end)
  it("raises the major for ! in the title", function()
    assert.equal("2.0.0", bump(pr(1, "feat!: new format")))
  end)
  it("raises the major for a BREAKING CHANGE footer", function()
    assert.equal("2.0.0", bump(pr(1, "fix: tidy", "Stuff.\n\nBREAKING CHANGE: old saves won't load")))
  end)
  it("gives nothing for docs-only changes", function()
    assert.is_nil(bump(pr(1, "docs: readme"), pr(2, "chore: bump"), pr(3, "test: more")))
  end)
  it("gives nothing when nothing merged", function() assert.is_nil(bump()) end)
  it("takes the highest bump when mixed", function()
    assert.equal("1.3.0", bump(pr(1, "fix: a"), pr(2, "feat: b"), pr(3, "docs: c")))
  end)
  it("counts a commit with no PR by its subject", function()
    assert.equal("1.2.4", bump({ title = "fix: direct commit" }))
    assert.is_nil(bump({ title = "Add README" }))
  end)
  it("ignores a note-looking footer on a commit with no PR", function()
    assert.is_nil(bump({ title = "docs: x", body = "BREAKING CHANGE: no" }))
  end)
  it("is 1.0.0 with no published release", function()
    assert.equal("1.0.0", Release.nextVersion(nil, { pr(1, "docs: x") }))
    assert.equal("1.0.0", Release.nextVersion(nil, {}))
  end)
  it("accepts a v prefix and rejects junk", function()
    assert.equal("2.0.0", Release.nextVersion("v1.9.9", { pr(1, "feat!: x") }))
    assert.has_error(function() Release.nextVersion("latest", {}) end)
  end)
  it("counts a PR arriving from several commits once", function()
    assert.equal("1.2.4", bump(pr(1, "fix: a"), pr(1, "fix: a"), pr(1, "fix: a")))
  end)
end)

describe("Release.notes", function()
  local same = { "Core.lua" }
  local function notes(previous, items, old, new)
    return (Release.notes(previous, items, old or same, new or same))
  end

  it("puts release notes under the right headings", function()
    local text = notes("1.0.0", {
      pr(1, "feat: window", "Release note: Officers get a new window."),
      pr(2, "fix: crash", "Release note: Fixed a crash on login."),
      pr(3, "feat!: format", "Release note: Saved data changed."),
    })
    assert.matches("## Before you update\n[^#]*%- Saved data changed%.", text)
    assert.matches("## New\n%- Officers get a new window%.", text)
    assert.matches("## Fixed\n%- Fixed a crash on login%.", text)
  end)
  it("leaves out a docs PR whose note is none, and omits empty headings", function()
    local text = notes("1.0.0", {
      pr(1, "docs: x", "Release note: none"), pr(2, "fix: y", "Release note: Fixed y."),
    })
    assert.is_nil(text:find("docs", 1, true))
    assert.is_nil(text:find("## New", 1, true))
  end)
  it("falls back to the title, marked, when a feat or fix has no real note", function()
    local items = { pr(1, "feat: window", "Release note: none"), pr(2, "fix: crash", "no note here") }
    local text, reword = Release.notes("1.0.0", items, same, same)
    assert.matches("%- feat: window" .. Release.REWORD_MARK:gsub("%p", "%%%0"), text)
    assert.matches("%- fix: crash", text)
    assert.same({ "feat: window", "fix: crash" }, reword)
  end)
  it("falls back to the title for a breaking PR without a note", function()
    local text = notes("1.0.0", { pr(1, "refactor!: rename", "") })
    assert.matches("## Before you update\n[^#]*%- refactor!: rename", text)
  end)
  it("says full restart when the .toc file list changed", function()
    local text = notes("1.0.0", {}, { "Core.lua" }, { "Core.lua", "New.lua" })
    assert.matches("start it again", text)
    assert.is_nil(text:find("/reload", 1, true))
  end)
  it("says /reload when the file list is the same, in any order", function()
    local text = notes("1.0.0", {}, { "A.lua", "B.lua" }, { "B.lua", "A.lua" })
    assert.matches("/reload", text)
    assert.is_nil(text:find("start it again", 1, true))
  end)
  it("detects a removed file", function() assert.is_true(Release.fileListChanged({ "A", "B" }, { "A" })) end)
  it("says fresh install for the first release, with no restart question", function()
    local text = notes(nil, { pr(1, "feat: x", "Release note: Hello.") }, nil, { "Core.lua" })
    assert.matches("fresh install", text)
    assert.is_nil(text:find("/reload", 1, true))
    assert.is_nil(text:find("start it again", 1, true))
  end)
  it("lists a PR arriving from several commits once", function()
    local one = pr(1, "fix: a", "Release note: Fixed a.")
    local text = notes("1.0.0", { one, one })
    local _, count = text:gsub("Fixed a%.", "")
    assert.equal(1, count)
  end)
end)

describe("Release.plan", function()
  it("gives the version and notes together, or nil when no release is due", function()
    local plan = Release.plan({
      previous = "1.0.0", items = { pr(1, "fix: a", "Release note: Fixed a.") },
      oldFiles = { "Core.lua" }, newFiles = { "Core.lua" },
    })
    assert.equal("1.0.1", plan.version)
    assert.matches("Fixed a%.", plan.notes)
    assert.is_nil(Release.plan({ previous = "1.0.0", items = { pr(1, "docs: a") } }))
  end)
end)
